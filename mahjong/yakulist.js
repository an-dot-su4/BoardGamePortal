export function renderYakuList(root) {
  root.replaceChildren(h('div', { class: 'stack' },
    h('p', { class: 'muted' }, 'アガるには、どれか1つ以上の役が必要です。翻が多いほど点数が高くなります。「鳴き」の列は、ポン・チーしたときの翻（× は鳴くとつかない）。ドラは役ではありません。'),
    YAKU.map(g => h('section', { class: 'stack' },
      h('h2', { class: 'section-title' }, g.group),
      h('div', { class: 'mj-yaku-list' }, g.list.map(([name, yomi, han, open, desc, ex]) => h('div', { class: 'panel mj-yaku' },
        h('div', { class: 'row' },
          h('strong', { class: 'mj-yaku-name' }, name), h('span', { class: 'small muted' }, yomi),
          h('span', { class: 'spacer' }),
          h('span', { class: 'tag' }, `門前 ${han}`), h('span', { class: 'tag' }, `鳴き ${open}`)),
        h('p', { class: 'small' }, desc),
        ex ? h('div', { class: 'mj-row mj-example' }, parse(ex).map(t => tileEl(t, { size: 'sm' }))) : null,
      ))))),
  ));
}
